// ---------- 规范名归一（空格/全角括号），未命中 KP2CANON 时应用 ----------
function autoNormalize(name) {
  return String(name)
    .replace(/（/g, '(').replace(/）/g, ')')
    .replace(/([A-Za-z0-9/]+)\s+(?=[\u4e00-\u9fa5])/g, '$1')   // 英数后贴中文的空格
    .replace(/(?<=[\u4e00-\u9fa5])\s+(?=[A-Za-z0-9/]+)/g, ''); // 中文后贴英数的空格
}

/** kp_node 名称 -> { canon, domain }；canon 唯一确定 domain（CASE/ESSAY 由调用方覆盖为 10/11） */
function resolveKp(name) {
  const canon = KP2CANON[name] || autoNormalize(name);
  let domain = CANON2DOMAIN[canon];
  if (!domain) {
    for (const [re, d] of KEYWORD_DOMAIN) { if (re.test(canon)) { domain = d; break; } }
  }
  return { canon, domain };
}

