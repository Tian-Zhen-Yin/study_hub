function aggregate(list, map, label) {
  const agg = {}; let unmapped = [];
  for (const {name, cnt} of list) {
    const key = map[name];
    if (!key) { unmapped.push(`${name}(${cnt})`); continue; }
    agg[key] = (agg[key] || 0) + cnt;
  }
  if (unmapped.length) console.log(`[未映射-${label}] ${unmapped.join(', ')}`);
  return agg;
}

